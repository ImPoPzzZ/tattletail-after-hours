"""Writes src/RecalledVoiceData.cs from the reviewed voice-line document (docs/RECALLED_VOICE_LINES.md).

The document is the source of truth: change a line there (keep its ID), run this, build.
"""
import os, re

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))

# who says a line, from the start of its ID (longest prefix wins)
WHO = [
    ('CALL-NN', 'Pip'), ('CALL-THE', 'Theo'), ('CALL-JUN', 'June'), ('CALL-MOS', 'Moss'),
    ('ARG-THE', 'Theo'), ('ARG-JUN', 'June'), ('ARG-MOS', 'Moss'), ('ARG-ASK', 'You'), ('ARG-SOLO', 'June'),
    ('TAPE-WG', 'Waygetter'), ('JUN', 'June'), ('THE', 'Theo'), ('MOS', 'Moss'), ('PA', 'Waygetter'),
    ('TOY', 'A toy'), ('PAT', 'Patches'), ('DSP', 'Display Model'), ('HAL', 'Hall Monitor'), ('PAP', 'Papa'),
    ('MAM', 'Mama'), ('NN', 'Pip'), ('RAD', 'Radio'), ('FORT', 'Sign'),
]
# lines that are a sound, not words
SOUND = {'PAT-AFTER': '(a tiny toy squeak)', 'MAM-AFTER': '(a cassette eject click, then silence)',
         'CALL-SFX': '(a crash, then static. The line goes dead.)'}
# the game says it the way the rest of the game does
US = {'neighbourhood': 'neighborhood', 'authorised': 'authorized', 'favourite': 'favorite', 'practising': 'practicing',
      'Armour': 'Armor', 'armour': 'armor', 'behaviour': 'behavior', 'torch': 'flashlight', 'metres': 'meters'}

doc = open('docs/RECALLED_VOICE_LINES.md', encoding='utf-8', newline='').read().replace('\r\n', '\n')
rows = []
for line in doc.split('\n'):
    m = re.match(r'^[-> ]+`([A-Z0-9-]+)`(.*)$', line)
    if not m:
        continue
    id_, rest = m.group(1), m.group(2)
    if id_ in SOUND:
        text = SOUND[id_]
    else:
        q = re.search(r'"(.+)"', rest)
        if not q:
            continue
        text = q.group(1)
    for k, v in US.items():
        text = text.replace(k, v)
    who = ''
    for prefix, name in WHO:
        if id_ == prefix or id_.startswith(prefix + '-'):
            who = name
            break
    if id_ in SOUND and id_ != 'CALL-SFX':
        who = ''           # (a sound has no name tab)
    rows.append((id_, who, text))

cs = ['// Generated by tools/gen_voice.py from docs/RECALLED_VOICE_LINES.md. Edit the document, not this file.',
      'using System.Collections.Generic;', '', 'namespace KaleidoscopeEndless', '{',
      '    /// <summary>Every written line in Recalled by its ID, and the groups they come in (JUN-ARR-1, JUN-ARR-2... are the group JUN-ARR).</summary>',
      '    public static class RcVoiceData', '    {',
      '        private static readonly Dictionary<string, RcSay> _lines = new Dictionary<string, RcSay>();',
      '        private static readonly Dictionary<string, List<string>> _groups = new Dictionary<string, List<string>>();',
      '        private static readonly List<string> _none = new List<string>();', '',
      '        public static bool Has(string id) { return _lines.ContainsKey(id); }',
      '        public static RcSay Line(string id) { RcSay s; return _lines.TryGetValue(id, out s) ? s : new RcSay { Who = "", Text = "" }; }',
      '        public static List<string> Group(string prefix) { List<string> g; return _groups.TryGetValue(prefix, out g) ? g : _none; }', '',
      '        private static void Add(string id, string who, string text)',
      '        {', '            _lines[id] = new RcSay { Who = who, Text = text };',
      '            int dash = id.LastIndexOf(\'-\');',
      '            if (dash < 0 || dash == id.Length - 1) return;',
      '            for (int i = dash + 1; i < id.Length; i++) if (!char.IsDigit(id[i])) return;',
      '            string g = id.Substring(0, dash);', '            List<string> l;',
      '            if (!_groups.TryGetValue(g, out l)) _groups[g] = l = new List<string>();',
      '            l.Add(id);', '        }', '',
      '        static RcVoiceData()', '        {']
for id_, who, text in rows:
    cs.append('            Add("%s", "%s", "%s");' % (id_, who, text.replace('\\', '\\\\').replace('"', '\\"')))
cs += ['        }', '    }', '}', '']
open('src/RecalledVoiceData.cs', 'w', encoding='utf-8', newline='').write('\r\n'.join(cs))
print(len(rows), 'lines')
