"""Writes src/RecalledLines.cs from the reviewed lore document (docs/RECALLED_MISSION_LORE.md).

The document is the source of truth: change a line there (keep its ID), run this, build.
Jobs 23 and 24 are scenes with their own lines (RcScenes), so they're left out here.
"""
import os, re

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
WHO = {'J': 'June', 'T': 'Theo', 'M': 'Moss'}
US = {'metres': 'meters', 'armour': 'armor', 'behaviour': 'behavior', 'colour': 'color'}
LAST_JOB = 25
SCENES = (23, 24)   # (the call and the argument are scenes of their own: see RcScenes)

doc = open('docs/RECALLED_MISSION_LORE.md', encoding='utf-8', newline='').read().replace('\r\n', '\n')
out = []
for line in doc.split('\n'):
    m = re.match(r'^- `MIS-(\d\d)-(B|A2?)`(.*)$', line)
    if not m or int(m.group(1)) > LAST_JOB or int(m.group(1)) in SCENES:
        continue
    job, kind, rest = int(m.group(1)) - 1, m.group(2), m.group(3)
    for who, text in re.findall(r'\*\*([JTM]):\*\*\s*"(.*?)"(?=\s*(?:\*\*|$))', rest):
        for k, v in US.items():
            text = text.replace(k, v)
        out.append((job, 'false' if kind == 'B' else 'true', WHO[who], text))

cs = ['// Generated by tools/gen_lines.py from docs/RECALLED_MISSION_LORE.md. Edit the document, not this file.',
      'using System.Collections.Generic;', '', 'namespace KaleidoscopeEndless', '{',
      '    /// <summary>One line the kids say.</summary>',
      '    public struct RcSay { public string Who, Text; }', '',
      '    /// <summary>The story round each job: what a kid says when you pick it up (Before), and when you hand it in (After).</summary>',
      '    public static class RcLines', '    {',
      '        private static readonly Dictionary<int, List<RcSay>> _lines = new Dictionary<int, List<RcSay>>();',
      '        private static readonly List<RcSay> _none = new List<RcSay>();', '',
      '        public static List<RcSay> Before(int job) { List<RcSay> l; return _lines.TryGetValue(job * 2, out l) ? l : _none; }',
      '        public static List<RcSay> After(int job) { List<RcSay> l; return _lines.TryGetValue(job * 2 + 1, out l) ? l : _none; }', '',
      '        /// <summary>Which kid gives you the job: the one who tells you why it matters.</summary>',
      '        public static string Teller(int job) { List<RcSay> b = Before(job); return b.Count > 0 ? b[0].Who : "June"; }', '',
      '        private static void Add(int job, bool after, string who, string text)',
      '        {', '            int key = job * 2 + (after ? 1 : 0);', '            List<RcSay> l;',
      '            if (!_lines.TryGetValue(key, out l)) _lines[key] = l = new List<RcSay>();',
      '            l.Add(new RcSay { Who = who, Text = text });', '        }', '',
      '        static RcLines()', '        {']
for job, after, who, text in out:
    cs.append('            Add(%d, %s, "%s", "%s");' % (job, after, who, text.replace('\\', '\\\\').replace('"', '\\"')))
cs += ['        }', '    }', '}', '']
open('src/RecalledLines.cs', 'w', encoding='utf-8', newline='').write('\r\n'.join(cs))
print(len(out), 'lines')
